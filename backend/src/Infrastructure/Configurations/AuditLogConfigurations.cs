using Core.ValueObjects;
using Infrastructure.Constants;
using Infrastructure.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Npgsql.EntityFrameworkCore.PostgreSQL.Metadata;

namespace Infrastructure.Configurations;

public class AuditLogConfigurations : IEntityTypeConfiguration<AuditLogEntity>
{
    public void Configure(EntityTypeBuilder<AuditLogEntity> builder)
    {
        builder.HasKey(x => x.AuditLogId);

        builder.HasOne(x => x.EntityTypeEntity).WithMany(x => x.AuditLogs).HasForeignKey(x => x.EntityTypeId).IsRequired();
        builder.HasOne(x => x.OperationEntity).WithMany(x => x.AuditLogs).HasForeignKey(x => x.OperationId).IsRequired();

        builder.Property(x => x.Snapshot).HasColumnType("jsonb");

        // Generated by the trigger, not an identity column: the position is per organisation, and Npgsql would default to identity.
        builder.Property(x => x.Sequence)
            .ValueGeneratedOnAdd()
            .HasAnnotation("Npgsql:ValueGenerationStrategy", NpgsqlValueGenerationStrategy.None);
        builder.Property(x => x.PreviousHash).HasMaxLength(Hash.Length).ValueGeneratedOnAdd();
        builder.Property(x => x.Hash).HasMaxLength(Hash.Length).ValueGeneratedOnAdd();

        builder.HasIndex(x => new { x.EntityTypeId, x.EntityId });
        builder.HasIndex(x => x.OrganizationId);

        builder.HasIndex(x => new { x.OrganizationId, x.Sequence }).IsUnique();

        builder.ToTable(TableNames.AuditLogs, Schemas.Service);
    }
}
